"""Write human-readable run artifacts for the demo, repo, and submission."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .config import Settings
from .events import EventBus


def _escape_cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def write_run_outputs(
    settings: Settings,
    mission: dict[str, Any],
    result: dict[str, Any],
    bus: EventBus,
    report_path: Path | None = None,
) -> Path:
    latest = Path(settings.artifacts_dir) / "latest"
    latest.mkdir(parents=True, exist_ok=True)
    report_path = report_path or latest / "report.md"

    events = bus.history
    shots = [event["shot"] for event in events if event.get("shot")]
    status = "SUCCESS" if result.get("success") else "FAILED"

    lines = [
        "# AegisWeb — Mission Report",
        "",
        f"**Status:** `{status}`  ",
        f"**Mission:** {mission.get('task', '')}  ",
        f"**Run:** `{result.get('run_id', '')}`  ",
        f"**Duration:** {result.get('duration_seconds', 0):.1f}s  ",
        "",
        "## Outcome",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Product | {_escape_cell(result.get('product') or '—')} |",
        f"| Price captured | {_escape_cell(result.get('price') or '—')} |",
        f"| Consent banner | {_escape_cell(result.get('consent_method') or '—')} |",
        f"| Trackers blocked | {result.get('trackers_blocked', 0)} |",
        f"| Tabs orchestrated | {result.get('tabs', 0)} |",
        f"| Form submitted | {result.get('form_submitted', False)} |",
        f"| Cloud sync | {_escape_cell(result.get('cloud_status') or 'local only')} |",
        "",
        "## Story",
        "",
        "AegisWeb opened the storefront, found the consent overlay, rejected all",
        "non-essential cookies, captured the first product's price, handed that value",
        "across tabs, and verified the research form submission.",
        "",
        "## Trace",
        "",
        "| t | event | detail |",
        "| ---: | --- | --- |",
    ]
    for event in events:
        if event.get("kind") in {"screenshot"}:
            continue
        lines.append(
            f"| +{event.get('elapsed', 0):.1f}s | {_escape_cell(event.get('kind', ''))}: "
            f"{_escape_cell(event.get('title', ''))} | {_escape_cell(event.get('detail', ''))} |"
        )

    if shots:
        lines += ["", "## Evidence", ""]
        for shot in shots:
            name = shot.split("/", 1)[-1]
            lines.append(f"![{name}]({name})")
            lines.append("")

    if result.get("error"):
        lines += ["", "## Error", "", "```", str(result["error"]), "```", ""]

    lines += [
        "",
        "---",
        "",
        "Generated by AegisWeb. The demo storefront and form are local; no real",
        "purchases or personal data are involved.",
        "",
    ]
    report_path.write_text("\n".join(lines), encoding="utf-8")

    run_json = latest / "run.json"
    run_json.write_text(
        json.dumps({"mission": mission, "result": result, "events": events}, indent=2, default=str),
        encoding="utf-8",
    )
    return report_path
